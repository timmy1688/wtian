def shi_yanggan(gan: str) -> bool:
    """是否阳干（甲丙戊庚壬）。"""
    return TIANGAN.index(gan) % 2 == 0


def jiazi_xuhao(ganzhi: str) -> int:
    """
    干支在六十甲子中的序号（甲子为 0）。
    天干序 g、地支序 z 同奇偶时，序号 n 满足 n ≡ g (mod 10)、n ≡ z (mod 12)，解得 n = (6g - 5z) mod 60。
    """
    g = TIANGAN.index(ganzhi[0])
    z = DIZHI.index(ganzhi[1])
    if g % 2 != z % 2:
        raise ValueError(f"invalid ganzhi: {ganzhi}")
    return (6 * g - 5 * z) % 60


def xuhao_jiazi(xuhao: int) -> str:
    xuhao %= 60
    return TIANGAN[xuhao % 10] + DIZHI[xuhao % 12]
