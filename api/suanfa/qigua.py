# 铜钱字面计 2、背面计 3，三枚之和：6 老阴、7 少阳、8 少阴、9 老阳
QIAN_ZI, QIAN_BEI = 2, 3
YANG_SHU = (7, 9)
DONG_SHU = (6, 9)


def qiu_jingua(sanyao: list) -> str:
    """三爻（自下而上）对应的八卦。"""
    return BAGUA[tuple(sanyao)]


def _cheng_gua(liuyao: list) -> dict:
    xiagua, shanggua = qiu_jingua(liuyao[0:3]), qiu_jingua(liuyao[3:6])
    mingcheng, guaxu = LIUSHISI_GUA[(xiagua, shanggua)]
    return {"gua": mingcheng, "number": guaxu, "yao": liuyao, "xiagua": xiagua, "shanggua": shanggua}


def pai_gua(yao: list, dongyao: list) -> dict:
    """
    由本卦六爻与动爻位置推出本卦、变卦：动爻阴阳互变即得变卦。
    :raises ValueError: 爻象或动爻不合法
    """
    if len(yao) != 6 or any(v not in (0, 1) for v in yao):
        raise ValueError("yao must be six values of 0 or 1")
    dongyao = sorted(set(dongyao))
    if any(p < 1 or p > 6 for p in dongyao):
        raise ValueError("moving positions must be within 1-6")

    bianyao = [1 - v if (i + 1) in dongyao else v for i, v in enumerate(yao)]
    bengua = _cheng_gua(list(yao))
    bengua["dongyao"] = dongyao
    return {"bengua": bengua, "biangua": _cheng_gua(bianyao)}


def yao_yi_yao() -> tuple:
    """抛三枚铜钱得一爻：(阴阳, 是否动爻)。老阴老阳为动爻。"""
    he = sum(random.choice([QIAN_ZI, QIAN_BEI]) for _ in range(3))
    return (1 if he in YANG_SHU else 0), he in DONG_SHU


def qi_gua() -> dict:
    """自下而上摇六次成卦，返回本卦与变卦。"""
    yao, dongyao = [], []
    for weizhi in range(1, 7):
        yinyang, shi_dong = yao_yi_yao()
        yao.append(yinyang)
        if shi_dong:
            dongyao.append(weizhi)
    return pai_gua(yao, dongyao)
